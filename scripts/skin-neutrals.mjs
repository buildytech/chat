// Writes apps/chat-web/src/lib/theme/magazine/skin-neutrals.ts: the lightness (and alpha) of every neutral token of every
// skin, light and dark, read from the registry skin CSS (registry/svelte/src/styles/skins/<id>.css; the default theme:
// styles/theme.css). Port of codegen-x/ui8kit packages/theme-model/scripts/skin-neutrals.ts (same CSS, same table): a
// custom palette (magazine-theme v2) tints these tokens and keeps the skin's lightness.
// `node scripts/skin-neutrals.mjs` writes, `--check` fails when the file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = `${ROOT}apps/chat-web/src/lib/theme/magazine/skin-neutrals.ts`;
const ids = /export const SKIN_IDS = \[([\s\S]*?)\] as const/.exec(readFileSync(`${ROOT}apps/chat-web/src/lib/theme/magazine/ids.ts`, "utf8"))[1].match(/"([a-z0-9-]+)"/g).map((s) => s.slice(1, -1));
const tokens = /NEUTRAL_TOKENS = \[([\s\S]*?)\] as const/.exec(readFileSync(`${ROOT}apps/chat-web/src/lib/theme/magazine/neutral-tokens.ts`, "utf8"))[1].match(/"([a-z0-9-]+)"/g).map((s) => s.slice(1, -1));

const round1 = (n) => Math.round(n * 10) / 10;
function value(css, name, nth, skin) {
	const all = [...css.matchAll(new RegExp(`--${name}:\\s*hsl\\(\\s*[\\d.]+\\s+[\\d.]+%\\s+([\\d.]+)%\\s*(?:/\\s*([\\d.]+)(%?))?\\s*\\)`, "g"))];
	const m = all[nth];
	if (all.length !== 2 || !m) throw new Error(`${skin}: --${name} needs one light and one dark hsl() value, found ${all.length}`);
	const l = round1(Number(m[1]));
	if (m[2] === undefined) return `[${l}]`;
	const a = m[3] ? Number(m[2]) / 100 : Number(m[2]);
	return `[${l}, ${Math.round(a * 100) / 100}]`;
}
const file = (id) => `${ROOT}registry/svelte/src/styles/${id === "default" ? "theme.css" : `skins/${id}.css`}`;
export function build() {
	const rows = ["default", ...ids].map((id) => {
		const css = readFileSync(file(id), "utf8");
		const mode = (nth) => `[${tokens.map((t) => value(css, t, nth, id)).join(", ")}]`;
		return `  "${id}": { light: ${mode(0)}, dark: ${mode(1)} },`;
	});
	return `// Generated by scripts/skin-neutrals.mjs from the registry skin CSS (\`npm run theme:neutrals\`). Do not edit by hand.
// Same table as codegen-x/ui8kit packages/theme-model/src/skin-neutrals.ts (same CSS). The neutral tokens of every skin in the order of NEUTRAL_TOKENS (neutral-tokens.ts): [lightness %] or [lightness %, alpha];
// "default" is the kit's own theme (no skin).
export type Neutral = readonly [number] | readonly [number, number];
export const SKIN_NEUTRALS: Record<string, { light: readonly Neutral[]; dark: readonly Neutral[] }> = {
${rows.join("\n")}
};
`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const text = build();
	if (process.argv.includes("--check")) {
		let now = "";
		try { now = readFileSync(OUT, "utf8"); } catch {}
		if (now !== text) { console.error("skin-neutrals.ts is stale: run npm run theme:neutrals"); process.exit(1); }
		console.log("skin-neutrals: current");
	} else {
		writeFileSync(OUT, text);
		console.log(`skin-neutrals: ${ids.length + 1} skins x ${tokens.length} tokens -> ${OUT}`);
	}
}
