/**
 * Pinned UI8Kit registry snapshot (build time, never at runtime and never from the chat).
 *
 *   node scripts/registry-snapshot.mjs          fetch registry/registry.config.json items + registryDependencies
 *                                               (transitively, like `npx ui8kit add`), write the lockfile and vendor
 *   node scripts/registry-snapshot.mjs --css    offline: regenerate apps/chat-web/src/registry/preview-kit.css only
 *   node scripts/registry-snapshot.mjs --check  offline: every vendored file matches the sha256 in the lockfile
 *
 * Outputs (all generated, do not edit by hand):
 *   registry/registry.lock.json                      item URLs, sha256 of each item JSON and of each file
 *   apps/chat-web/src/registry/svelte/**             the sources (Preview imports the real organisms)
 *   apps/chat-web/src/registry/files.json            the same sources as text (ZIP pack)
 *   packages/builder-core/src/catalog/sources.json   catalog block -> registry item, variant -> props presets
 *                                                    (from compose-gen block specs at the pinned commit), Lucide names
 */
import { createHash } from "node:crypto";
import { previewCss } from "./registry-preview-css.mjs";
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONFIG = join(ROOT, "registry/registry.config.json");
const LOCK = join(ROOT, "registry/registry.lock.json");
const VENDOR = join(ROOT, "apps/chat-web/src/registry/svelte");
const FILES_JSON = join(ROOT, "apps/chat-web/src/registry/files.json");
const SOURCES_JSON = join(ROOT, "packages/builder-core/src/catalog/sources.json");
const PREVIEW_CSS = join(ROOT, "apps/chat-web/src/registry/preview-kit.css");
const APP_CSS = join(ROOT, "apps/chat-web/src/styles/chat-theme.css");
const TAILWIND_THEME = join(ROOT, "node_modules/tailwindcss/theme.css");

/** Registry folder per item type (ui8kit CLI TYPE_TO_FOLDER). */
const TYPE_FOLDER = {
	"registry:lib": "lib",
	"registry:utils": "utils",
	"registry:ui": "components/ui",
	"registry:component": "components",
	"registry:composite": "components",
	"registry:block": "blocks"
};

const sha256 = (text) => `sha256:${createHash("sha256").update(text, "utf8").digest("hex")}`;
const json = (value) => `${JSON.stringify(value, null, "\t")}\n`;
const SAFE_PATH = /^(?!.*\.\.)[A-Za-z0-9_][A-Za-z0-9_./-]*$/;

function write(path, content) {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, content);
}

async function fetchText(url) {
	const res = await fetch(url);
	if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
	return { status: res.status, text: await res.text() };
}

function scopedCss(files) {
	return previewCss({
		theme: files["styles/theme.css"],
		kit: files["styles/kit.css"],
		appCss: readFileSync(APP_CSS, "utf8"),
		tailwindTheme: readFileSync(TAILWIND_THEME, "utf8"),
		header: "/* Code generated by scripts/registry-preview-css.mjs from the vendored registry styles/theme.css and styles/kit.css. DO NOT EDIT. */"
	});
}

function check() {
	const lock = JSON.parse(readFileSync(LOCK, "utf8"));
	const files = JSON.parse(readFileSync(FILES_JSON, "utf8"));
	let bad = 0;
	const expected = new Set();
	for (const item of lock.items) {
		for (const file of item.files) {
			expected.add(file.path);
			const disk = join(VENDOR, file.path);
			const text = existsSync(disk) ? readFileSync(disk, "utf8") : null;
			if (text === null || sha256(text) !== file.sha256) {
				console.error(`mismatch ${file.path}`);
				bad += 1;
			}
			if (files[file.path] !== text) {
				console.error(`files.json differs ${file.path}`);
				bad += 1;
			}
		}
	}
	for (const path of Object.keys(files)) if (!expected.has(path)) { console.error(`unlocked ${path}`); bad += 1; }
	const sources = JSON.parse(readFileSync(SOURCES_JSON, "utf8"));
	if (sources.lockDigest !== sha256(JSON.stringify(lock.items))) { console.error("sources.json lockDigest is stale"); bad += 1; }
	if (!existsSync(PREVIEW_CSS) || readFileSync(PREVIEW_CSS, "utf8") !== scopedCss(files)) { console.error("preview-kit.css is stale"); bad += 1; }
	console.log(`${lock.items.length} items, ${expected.size} files: ${bad ? `${bad} problem(s)` : "all sha256 match"}`);
	return bad === 0;
}

async function snapshot() {
	const config = JSON.parse(readFileSync(CONFIG, "utf8"));
	const base = `${config.registry}/${config.runtime}`;
	const indexUrl = `${base}/index.json`;
	const indexRes = await fetchText(indexUrl);
	const index = JSON.parse(indexRes.text);
	const byName = new Map(index.components.map((entry) => [entry.name, entry]));

	const items = new Map();
	const queue = config.blocks.map((block) => block.item);
	while (queue.length) {
		const name = queue.shift();
		if (items.has(name)) continue;
		const entry = byName.get(name);
		if (!entry) throw new Error(`registry item ${name} is not in ${indexUrl}`);
		const folder = TYPE_FOLDER[entry.type];
		if (!folder) throw new Error(`registry item ${name}: unsupported type ${entry.type}`);
		const url = `${base}/${folder}/${name}.json`;
		const res = await fetchText(url);
		const item = JSON.parse(res.text);
		items.set(name, { url, status: res.status, raw: res.text, item });
		for (const dep of item.registryDependencies ?? []) queue.push(dep);
	}

	rmSync(VENDOR, { recursive: true, force: true });
	const files = {};
	const lockItems = [];
	const npm = new Set();
	for (const [name, { url, status, raw, item }] of [...items].sort(([a], [b]) => a.localeCompare(b))) {
		const locked = [];
		for (const file of item.files ?? []) {
			if (!SAFE_PATH.test(file.path)) throw new Error(`${name}: unsafe path ${file.path}`);
			if (files[file.path] !== undefined && files[file.path] !== file.content) throw new Error(`${file.path} differs between items`);
			files[file.path] = file.content;
			write(join(VENDOR, file.path), file.content);
			locked.push({ path: file.path, sha256: sha256(file.content) });
		}
		for (const dep of item.dependencies ?? []) npm.add(dep);
		lockItems.push({
			name,
			type: item.type,
			url,
			status,
			sha256: sha256(raw),
			registryDependencies: item.registryDependencies ?? [],
			dependencies: item.dependencies ?? [],
			files: locked
		});
	}
	const sortedFiles = Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
	write(FILES_JSON, json(sortedFiles));
	const lock = {
		format: "buildy-registry-lock",
		version: 1,
		registry: base,
		index: { url: indexUrl, sha256: sha256(indexRes.text), lastUpdated: index.lastUpdated },
		roots: config.blocks.map((block) => block.item),
		npmDependencies: [...npm].sort(),
		items: lockItems
	};
	write(LOCK, json(lock));

	// Variant -> props presets from the compose-gen block specs (the JSON compose-gen writes from gallery blocks.ts).
	const blocks = {};
	const specsLock = [];
	for (const block of config.blocks) {
		const specUrl = `https://raw.githubusercontent.com/${config.specs.repo}/${config.specs.commit}/${config.specs.dir}/${block.spec}.json`;
		const res = await fetchText(specUrl);
		const spec = JSON.parse(res.text);
		specsLock.push({ spec: block.spec, url: specUrl, sha256: sha256(res.text) });
		const organismFile = files[block.organism];
		if (!organismFile) throw new Error(`${block.organism} is not part of the ${block.item} closure`);
		const variants = {};
		for (const variant of spec.variants) {
			const props = { ...spec.defaults, ...variant.set };
			for (const axis of Object.keys(props)) {
				if (!spec.axes[axis]?.includes(props[axis])) throw new Error(`${block.spec}/${variant.id}: ${axis}=${props[axis]} is not an axis value`);
				if (!new RegExp(`\\b${axis}\\??:`).test(organismFile)) throw new Error(`${block.organism} has no prop ${axis}`);
			}
			variants[variant.id] = { props, ...(variant.props?.action ? { action: true } : {}) };
		}
		blocks[block.catalogBlock] = {
			kind: block.kind,
			item: block.item,
			organism: block.organism,
			specId: spec.id,
			organismName: spec.organism,
			axes: spec.axes,
			defaults: spec.defaults,
			defaultVariant: spec.variants[0].id,
			variants,
			props: block.props,
			fallbackIcon: block.fallbackIcon
		};
	}
	const lucide = files["icons/lucide-icons.ts"] ?? "";
	const icons = [...lucide.matchAll(/^ {2}"([a-z0-9-]+)": \[/gm)].map((match) => match[1]);
	for (const block of Object.values(blocks)) {
		if (!icons.includes(block.fallbackIcon)) throw new Error(`fallback icon ${block.fallbackIcon} is not a Lucide name of the snapshot`);
	}
	const sources = {
		format: "buildy-catalog-sources",
		version: 1,
		registry: base,
		lockDigest: sha256(JSON.stringify(lockItems)),
		specs: { repo: config.specs.repo, commit: config.specs.commit, files: specsLock },
		npmDependencies: lock.npmDependencies,
		// Item graph for the ZIP: the closure of the organisms a page uses (like `npx ui8kit add`).
		items: Object.fromEntries(lockItems.map((item) => [item.name, { registryDependencies: item.registryDependencies, files: item.files.map((file) => file.path) }])),
		blocks,
		icons
	};
	write(SOURCES_JSON, json(sources));
	write(PREVIEW_CSS, scopedCss(sortedFiles));
	console.log(`${lockItems.length} items, ${Object.keys(files).length} files, ${icons.length} Lucide names, ${Object.keys(blocks).length} catalog block(s)`);
}

if (process.argv.includes("--check")) process.exit(check() ? 0 : 1);
else if (process.argv.includes("--css")) write(PREVIEW_CSS, scopedCss(JSON.parse(readFileSync(FILES_JSON, "utf8"))));
else await snapshot();
