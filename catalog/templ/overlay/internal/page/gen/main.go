// Command gen writes ../sections_gen.go (go generate ./internal/page): one case per registry block of
// ui/kit/ui8kit.lock.json (type registry:block, file blocks/<item>.templ), mapping the item to its templ component.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
)

const kit = "../../ui/kit"

var signature = regexp.MustCompile(`(?m)^templ ([A-Z][A-Za-z0-9]*)\(p ([A-Z][A-Za-z0-9]*Props)\)`)

func main() {
	raw, err := os.ReadFile(filepath.Join(kit, "ui8kit.lock.json"))
	if err != nil {
		fail(err)
	}
	var lock struct {
		Items map[string]struct {
			Name  string            `json:"name"`
			Type  string            `json:"type"`
			Files map[string]string `json:"files"`
		} `json:"items"`
	}
	if err := json.Unmarshal(raw, &lock); err != nil {
		fail(err)
	}
	var names []string
	for _, it := range lock.Items {
		if _, ok := it.Files["blocks/"+it.Name+".templ"]; ok && it.Type == "registry:block" {
			names = append(names, it.Name)
		}
	}
	sort.Strings(names)
	blocksImport := ""
	if len(names) > 0 {
		blocksImport = "\n\t\"github.com/ui8kit/codegen/generated/templ/blocks\""
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/page/gen (go generate ./internal/page) from ui/kit/ui8kit.lock.json. DO NOT EDIT.\n\n")
	b.WriteString("package page\n\nimport (\n\t\"encoding/json\"\n\t\"fmt\"\n\n\t\"github.com/a-h/templ\"" + blocksImport + "\n)\n\n")
	b.WriteString("// component is the templ block of a registry item with its props (page.json).\n")
	b.WriteString("func component(item string, props json.RawMessage) (templ.Component, error) {\n\tswitch item {\n")
	for _, name := range names {
		src, err := os.ReadFile(filepath.Join(kit, "blocks", name+".templ"))
		if err != nil {
			fail(err)
		}
		m := signature.FindSubmatch(src)
		if m == nil || string(m[1])+"Props" != string(m[2]) {
			fail(fmt.Errorf("blocks/%s.templ: no `templ X(p XProps)` component", name))
		}
		fmt.Fprintf(&b, "\tcase %q:\n\t\tvar p blocks.%s\n\t\tif err := json.Unmarshal(props, &p); err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\treturn blocks.%s(p), nil\n", name, m[2], m[1])
	}
	b.WriteString("\t}\n\treturn nil, fmt.Errorf(\"%q is not a registry block of ui/kit (ui8kit add it, then go generate)\", item)\n}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("sections_gen.go", out, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "page/gen:", err)
	os.Exit(1)
}
